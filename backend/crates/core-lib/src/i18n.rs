use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::sync::OnceLock;

/// Cache for translations to avoid rebuilding locale data on every access
static TRANSLATIONS_CACHE: OnceLock<HashMap<String, HashMap<String, String>>> = OnceLock::new();

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LocaleConfig {
    pub current: String,
}

impl Default for LocaleConfig {
    fn default() -> Self {
        Self {
            current: "en".to_string(),
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TranslationEntry {
    pub key: String,
    pub value: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Locale {
    pub code: String,
    pub name: String,
    pub translations: HashMap<String, String>,
}

impl Locale {
    pub fn new(code: &str, name: &str) -> Self {
        Self {
            code: code.to_string(),
            name: name.to_string(),
            translations: HashMap::new(),
        }
    }

    pub fn with_translations(mut self, translations: Vec<(&str, &str)>) -> Self {
        for (k, v) in translations {
            self.translations.insert(k.to_string(), v.to_string());
        }
        self
    }
}

